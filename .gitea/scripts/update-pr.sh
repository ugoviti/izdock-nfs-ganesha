#!/bin/bash
# update-pr.sh: commit the versions.env changes of tools/make-updates.sh --apply on BRANCH
# (recreated from the checked out commit, force pushed) and open its pull request, or
# refresh the one already open. Run by .gitea/workflows/updates.yml after the checkout
# (its token pushes the branch).
#   GITEA_SERVER, REPO (owner/name), TOKEN   Gitea API
#   BRANCH, BASE                             eg. auto/updates, master
#   REPORT                                   file with the make-updates output (PR body)
set -Eeuo pipefail
: "${GITEA_SERVER:?}" "${REPO:?}" "${TOKEN:?}" "${BRANCH:?}" "${BASE:?}" "${REPORT:?}"
api="$GITEA_SERVER/api/v1/repos/$REPO"
auth=(-H "Authorization: token $TOKEN" -H 'Content-Type: application/json')

# versions changed by the report: one "KEY current -> latest" line per UPDATE row
changes=$(awk '$4 ~ /^UPDATE/ { printf "%s %s -> %s\n", $1, $2, $3 }' "$REPORT")
title="update components: $(awk '{print $1}' <<< "$changes" | sed 's/_VER$//; s/_DIGEST$/ digest/' | paste -sd, - | sed 's/,/, /g')"
[ ${#title} -le 200 ] || title="update components ($(wc -l <<< "$changes") updates)"

git config user.name "nfs-ganesha-updates"
git config user.email "nfs-ganesha-updates@noreply.invalid"
git checkout -q -B "$BRANCH"
git add versions.env
git commit -q -F - <<MSG
$title

$changes

Generated by .gitea/workflows/updates.yml (tools/make-updates.sh --apply).
MSG
git push -q --force origin "HEAD:refs/heads/$BRANCH"

body=$(printf '%s\n\n```\n%s\n```\n\n%s\n' \
  "Weekly \`tools/make-updates.sh --apply\`: the checks of this pull request build and verify the image. Merge to release (master builds and publishes)." \
  "$(cat "$REPORT")" \
  "New majors and pinned components (\`<NAME>_PIN\`) are never applied. Closing this PR without merging skips these versions until next week's run.")

number=$(curl -fsS "${auth[@]}" "$api/pulls?state=open&limit=50" | jq -r --arg b "$BRANCH" '[.[] | select(.head.ref == $b)][0].number // empty')
payload=$(jq -n --arg t "$title" --arg b "$body" --arg h "$BRANCH" --arg base "$BASE" '{title: $t, body: $b, head: $h, base: $base}')
if [ -n "$number" ]; then
  curl -fsS "${auth[@]}" -X PATCH -d "$(jq '{title, body}' <<< "$payload")" "$api/pulls/$number" >/dev/null
  echo "pull request #$number refreshed: $title"
else
  number=$(curl -fsS "${auth[@]}" -X POST -d "$payload" "$api/pulls" | jq -r .number)
  echo "pull request #$number opened: $title"
fi
echo "number=$number" >> "${GITHUB_OUTPUT:-/dev/null}"
